let current = 'pt';

export function setLang(lang) {
  if (dict[lang]) current = lang;
  document.documentElement.lang = LANGS[current].html;
  return current;
}

export function getLang() { return current; }

export function t(key, vars = {}) {
  const table = dict[current] || dict.pt;
  let value = table[key];
  if (value === undefined) value = dict.en[key] ?? key;
  if (typeof value === 'string') {
    return value.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  }
  return value;
}

export function tr(key, vars) {
  const v = t(key, vars);
  return Array.isArray(v) ? v : [v];
}
